def booking_text(data):
    language = data.get('language', 'ru')
    return TEXT.get(language, TEXT['en'])


def invalid_preview_text(state):
    return booking_text(state)['invalid_preview']


def preview_text(data, choice):
    text = booking_text(data)
    values = [
        choice,
        data['travel_date'],
        data['people_count'],
        data['client_name'],
        data['phone'],
        data.get('email'),
        data.get('duration_days'),
        data.get('budget'),
        data.get('notes'),
    ]
    lines = [
        f'{label}: {value if value is not None and value != "" else text["missing"]}'
        for label, value in zip(text['labels'], values)
    ]
    labels = {
        'ru': {'hotel': 'Отель', 'transport': 'Транспорт'},
        'ky': {'hotel': 'Мейманкана', 'transport': 'Унаа'},
        'en': {'hotel': 'Hotel', 'transport': 'Transport'},
        'de': {'hotel': 'Hotel', 'transport': 'Transport'},
        'zh': {'hotel': '酒店', 'transport': '交通'},
    }.get(data.get('language', 'ru'), {'hotel': 'Hotel', 'transport': 'Transport'})
    lines.extend(
        f'{labels[item["kind"]]}: {item["name"]}'
        for item in data.get('selected_services', [])
        if item['kind'] in labels
    )
    return '\n\n' + text['heading'] + '\n' + '\n'.join(lines) + '\n\n' + text['confirm']
